// Writes the docs pages that come from elsewhere in the repository, so they cannot drift from it
// (ADR 0011): the CLI reference from the CLI's own help text, and the menu bar app's screenshots.
import { copyFile, mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { USAGE } from '../../../packages/dryfit/src/cli/main.ts';

const site = join(dirname(fileURLToPath(import.meta.url)), '..');
const repo = join(site, '..', '..');
const docs = join(site, 'src', 'content', 'docs');
const NOTICE = '{/* Generated by apps/site/scripts/generate.ts. Edit the source, not this file. */}';

interface Entry {
  readonly syntax: string;
  description: string;
  readonly options: string[];
}

/** Ends a sentence that does not already end in punctuation. */
/** Help-text prose as MDX: a placeholder such as `<consumer>` would otherwise be read as a JSX tag. */
const prose = (text: string) => text.replace(/(?<!`)<[\w-]+>(?!`)/g, (placeholder) => `\`${placeholder}\``);

const sentence = (text: string) => prose(/[.!?]$/.test(text) ? text : `${text}.`);

/** The help text's sections: a title line, then commands, each followed by its indented options. */
function parseUsage(usage: string) {
  const sections: { title: string; entries: Entry[] }[] = [];
  const notes: string[] = [];
  for (const line of usage.split('\n')) {
    if (line.trim() === '' || line.startsWith('Usage:')) continue;
    if (!line.startsWith(' ')) {
      if (/^[A-Z][a-z ]+$/.test(line)) sections.push({ title: line, entries: [] });
      else notes.push(line);
      continue;
    }
    const section = sections.at(-1);
    if (!section) throw new Error(`Help text line outside a section: ${line}`);
    const [syntax = '', description = ''] = line.trim().split(/\s{2,}(?=[A-Z(])/);
    const entry = section.entries.at(-1);
    // Indented past the option column and not a flag: the previous line's text, wrapped.
    if (line.startsWith('      ') && !line.trim().startsWith('-') && entry) {
      const last = entry.options.length - 1;
      if (last >= 0) entry.options[last] = `${entry.options[last]} ${line.trim()}`;
      else entry.description = `${entry.description} ${line.trim()}`;
    } else if (line.startsWith('      ')) entry?.options.push(line.trim());
    else section.entries.push({ syntax, description, options: [] });
  }
  return { sections, notes };
}

function cliReference(): string {
  const { sections, notes } = parseUsage(USAGE);
  const out = [
    '---',
    'title: CLI reference',
    'description: Every dryfit command and option, from the CLI’s own help text.',
    // Generated, so there is no file here to edit; the text lives in the CLI's USAGE.
    'editUrl: false',
    '---',
    '',
    NOTICE,
    '',
    `This page is the output of \`dryfit --help\`, laid out. ${prose(notes.join(' '))}`,
    '',
  ];
  for (const { title, entries } of sections) {
    out.push(`## ${title}`, '');
    for (const { syntax, description, options } of entries) {
      out.push(`### \`dryfit ${syntax}\``, '');
      if (description) out.push(sentence(description), '');
      for (const option of options) {
        const [flags = '', text] = option.split(/\s{2,}(?=[A-Z(])/);
        out.push(
          text
            ? `- \`${flags}\`: ${sentence(text)}`
            : `- ${flags
                .split(/\s{2,}/)
                .map((flag) => `\`${flag}\``)
                .join(', ')}`,
        );
      }
      if (options.length > 0) out.push('');
    }
  }
  return out.join('\n');
}

/** The menu bar app's screenshots, kept in `apps/site/screenshots` (captured from the running app by the menu bar's LiveCapture test). */
async function menuScreenshots(): Promise<void> {
  const source = join(site, 'screenshots');
  const target = join(site, 'public', 'menu');
  await mkdir(target, { recursive: true });
  for (const name of ['online', 'window-library'].flatMap((shot) => [
    `${shot}.light.png`,
    `${shot}.dark.png`,
  ]))
    await copyFile(join(source, name), join(target, name));
}

await mkdir(join(docs, 'reference'), { recursive: true });
await writeFile(join(docs, 'reference', 'cli.mdx'), `${cliReference()}\n`);
await menuScreenshots();
process.stdout.write('Generated the CLI reference and the menu screenshots.\n');
